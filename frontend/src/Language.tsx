const LanguageContext = createContext<{ language: Language; setLanguage: (language: Language) => void; t: (key: Key, values?: Values) => string } | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    const saved = localStorage.getItem('wiki-language');
    return saved === 'fi' || saved === 'sv' ? saved : 'en';
  });
  useEffect(() => { document.documentElement.lang = language; }, [language]);
  function chooseLanguage(next: Language) {
    localStorage.setItem('wiki-language', next);
    setLanguage(next);
  }
  // `{name}` in a translation is replaced by `values.name`.
  const t = (key: Key, values: Values = {}) =>
    (translations[language][key] ?? translations.en[key] ?? key).replace(/\{(\w+)\}/g, (_, name) => String(values[name]));
  return <LanguageContext.Provider value={{ language, setLanguage: chooseLanguage, t }}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider');
  return context;
}
